# List
my_list = [1, 2, 3, 4, 5]
print(my_list, type(my_list))

# length of list
print(len(my_list))

# append
my_list.append(6)

# indexing
print(my_list[0])  # first element
print(my_list[-1])  # last element

# slicing(list[start:end])
# print(my_list[1:4])
print(my_list[-3:])

for m in my_list:
    print(m)


# Tuple
my_tuple = (1, 2, 3, 4, 5)
print(my_tuple, type(my_tuple))


